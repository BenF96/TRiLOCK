-- ===================================================================
-- TRILOCK ACCESS CONTROL SYSTEM: SUPABASE POSTGRESQL PRODUCTION SCHEMA
-- Cloud Database: Supabase (PostgreSQL 15+)
-- ===================================================================

-- Timestamps are TIMESTAMP (no time zone) holding APP_TIMEZONE wall-clock time, exactly as
-- Laravel writes them. TIMESTAMPTZ + a UTC session stored every value 8h in the future
-- (see migration 2026_09_25_000003_store_timestamps_in_app_timezone).

-- Enable required extensions
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- -------------------------------------------------------------------
-- 1. USERS TABLE
-- -------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_student_id VARCHAR(50) UNIQUE,
    first_name VARCHAR(100),
    middle_name VARCHAR(100),
    last_name VARCHAR(100),
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    email_verified_at TIMESTAMP(0),
    password VARCHAR(255) NOT NULL,
    photo TEXT,
    role VARCHAR(30) NOT NULL DEFAULT 'student' CHECK (role IN ('admin', 'student', 'faculty', 'lab_tech')),
    status VARCHAR(20) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
    remember_token VARCHAR(100),
    created_at TIMESTAMP(0) DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Singapore'),
    updated_at TIMESTAMP(0) DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Singapore')
);

-- -------------------------------------------------------------------
-- 2. RFID CARDS TABLE
-- -------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.rfid_cards (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES public.users(id) ON DELETE CASCADE,
    card_uid VARCHAR(50) NOT NULL UNIQUE,
    status VARCHAR(20) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'disabled', 'lost')),
    assigned_at TIMESTAMP(0),
    created_at TIMESTAMP(0) DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Singapore'),
    updated_at TIMESTAMP(0) DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Singapore')
);

-- -------------------------------------------------------------------
-- 3. FINGERPRINTS TABLE (AS608 Sensor Slots 1-127)
-- -------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.fingerprints (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    fingerprint_id INTEGER NOT NULL CHECK (fingerprint_id BETWEEN 1 AND 127),
    status VARCHAR(20) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'disabled')),
    registered_at TIMESTAMP(0),
    created_at TIMESTAMP(0) DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Singapore'),
    updated_at TIMESTAMP(0) DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Singapore'),
    CONSTRAINT unique_fingerprint_slot UNIQUE (fingerprint_id)
);

-- -------------------------------------------------------------------
-- 4. ACCESS PINS TABLE (Keypad PIN Authentication)
-- -------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.access_pins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    pin_code VARCHAR(255) NOT NULL,
    offline_hash VARCHAR(64),
    status VARCHAR(20) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'disabled')),
    assigned_at TIMESTAMP(0),
    created_at TIMESTAMP(0) DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Singapore'),
    updated_at TIMESTAMP(0) DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Singapore')
);

-- -------------------------------------------------------------------
-- 5. DEVICES TABLE (ESP32 Nodes & ESP32-CAM)
-- -------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.devices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_name VARCHAR(150) NOT NULL,
    device_type VARCHAR(50) NOT NULL CHECK (device_type IN ('esp32_cam', 'esp32_main')),
    ip_address VARCHAR(45),
    mac_address VARCHAR(17),
    api_token VARCHAR(80) UNIQUE,
    status VARCHAR(20) NOT NULL DEFAULT 'online' CHECK (status IN ('online', 'offline')),
    last_seen TIMESTAMP(0),
    created_at TIMESTAMP(0) DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Singapore'),
    updated_at TIMESTAMP(0) DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Singapore')
);

-- -------------------------------------------------------------------
-- 6. ACCESS LOGS TABLE
-- -------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.access_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
    authentication_method VARCHAR(50) NOT NULL CHECK (authentication_method IN ('rfid', 'fingerprint', 'rfid_fingerprint', 'pin', 'multi_factor', 'multi_factor_offline', 'triple_auth', 'unauthorized', 'manual_remote')),
    access_type VARCHAR(20) NOT NULL CHECK (access_type IN ('entry', 'denied')),
    denial_reason VARCHAR(50),
    captured_image TEXT,
    door_status VARCHAR(30) NOT NULL DEFAULT 'locked',
    date DATE NOT NULL DEFAULT CURRENT_DATE,
    time TIME NOT NULL DEFAULT CURRENT_TIME,
    device_id BIGINT REFERENCES public.devices(id) ON DELETE SET NULL,
    created_at TIMESTAMP(0) DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Singapore'),
    updated_at TIMESTAMP(0) DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Singapore')
);

-- -------------------------------------------------------------------
-- 7. DOOR HARDWARE LOGS TABLE
-- -------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.door_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status VARCHAR(50) NOT NULL CHECK (status IN ('opened', 'closed', 'unlocked', 'locked', 'left_open')),
    opened_at TIMESTAMP(0),
    closed_at TIMESTAMP(0),
    locked_at TIMESTAMP(0),
    remarks TEXT,
    created_at TIMESTAMP(0) DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Singapore'),
    updated_at TIMESTAMP(0) DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Singapore')
);

-- -------------------------------------------------------------------
-- 8. SYSTEM SETTINGS TABLE
-- -------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    door_unlock_duration INTEGER NOT NULL DEFAULT 5,
    auto_lock BOOLEAN NOT NULL DEFAULT TRUE,
    camera_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    capture_entry BOOLEAN NOT NULL DEFAULT TRUE,
    buzzer_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    lab_name VARCHAR(150) NOT NULL DEFAULT 'Com Lab 1',
    created_at TIMESTAMP(0) DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Singapore'),
    updated_at TIMESTAMP(0) DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Singapore')
);

-- -------------------------------------------------------------------
-- 9. ENROLLMENT AUDIT LOGS TABLE
-- -------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.enrollment_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_token VARCHAR(64) NOT NULL,
    admin_id BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
    user_id BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
    step VARCHAR(50) NOT NULL,
    status VARCHAR(50) NOT NULL,
    payload JSONB,
    message TEXT,
    created_at TIMESTAMP(0) DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Singapore'),
    updated_at TIMESTAMP(0) DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Singapore')
);

-- -------------------------------------------------------------------
-- 10. LARAVEL SESSION & CACHE TABLES
-- -------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.password_reset_tokens (
    email VARCHAR(255) PRIMARY KEY,
    token VARCHAR(255) NOT NULL,
    created_at TIMESTAMP(0)
);

CREATE TABLE IF NOT EXISTS public.sessions (
    id VARCHAR(255) PRIMARY KEY,
    user_id BIGINT REFERENCES public.users(id) ON DELETE CASCADE,
    ip_address VARCHAR(45),
    user_agent TEXT,
    payload TEXT NOT NULL,
    last_activity INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS public.cache (
    key VARCHAR(255) PRIMARY KEY,
    value TEXT NOT NULL,
    expiration INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS public.cache_locks (
    key VARCHAR(255) PRIMARY KEY,
    owner VARCHAR(255) NOT NULL,
    expiration INTEGER NOT NULL
);

-- -------------------------------------------------------------------
-- INDEXES FOR HIGH PERFORMANCE QUERYING
-- -------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_rfid_card_uid ON public.rfid_cards(card_uid);
CREATE INDEX IF NOT EXISTS idx_fingerprint_slot ON public.fingerprints(fingerprint_id);
CREATE INDEX IF NOT EXISTS idx_devices_api_token ON public.devices(api_token);
CREATE INDEX IF NOT EXISTS idx_access_logs_user ON public.access_logs(user_id);
CREATE INDEX IF NOT EXISTS idx_access_logs_date ON public.access_logs(date);

-- Existing deployments: bring older tables up to the current shape
ALTER TABLE public.access_logs ADD COLUMN IF NOT EXISTS denial_reason VARCHAR(50);
ALTER TABLE public.access_pins ADD COLUMN IF NOT EXISTS offline_hash VARCHAR(64);
ALTER TABLE public.access_logs DROP CONSTRAINT IF EXISTS access_logs_authentication_method_check;
ALTER TABLE public.access_logs ADD CONSTRAINT access_logs_authentication_method_check CHECK (authentication_method IN ('rfid', 'fingerprint', 'rfid_fingerprint', 'pin', 'multi_factor', 'multi_factor_offline', 'triple_auth', 'unauthorized', 'manual_remote'));
ALTER TABLE public.door_logs DROP CONSTRAINT IF EXISTS door_logs_status_check;
ALTER TABLE public.door_logs ADD CONSTRAINT door_logs_status_check CHECK (status IN ('opened', 'closed', 'unlocked', 'locked', 'left_open'));
CREATE INDEX IF NOT EXISTS idx_enrollment_logs_session ON public.enrollment_logs(session_token);
CREATE INDEX IF NOT EXISTS idx_sessions_user ON public.sessions(user_id);

